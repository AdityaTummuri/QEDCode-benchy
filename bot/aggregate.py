"""Rebuild leaderboard/leaderboard.json and the README statistics from accepted submissions.

    python3 bot/aggregate.py            # write the files
    python3 bot/aggregate.py --check    # exit 1 if they are out of date (nothing written)

Accepted = merged into results/submissions/ after review. Every record is validated again here
(defence in depth); one that fails is left out and listed. Aggregates are only ever generated by
this script, never edited by hand. Output is deterministic (no "generated at" clock time).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from benchy.reports.stats import paired, summarize_condition  # noqa: E402
from benchy.submission.validate import known_suites, validate_bytes  # noqa: E402

START = "<!-- benchy:stats:start -->"
END = "<!-- benchy:stats:end -->"
COMMUNITY = "community-reported (schema-validated)"
REPRODUCED = "independently reproduced"


def load_accepted(root: Path) -> tuple[list[dict], list[str]]:
    suites = known_suites(root / "suites")
    records, skipped = [], []
    for path in sorted((root / "results" / "submissions").glob("*.json")):
        record, problems = validate_bytes(path.read_bytes(), suites)
        if problems or record is None or path.stem != record["submission_id"]:
            skipped.append(path.name)
            continue
        records.append(record)
    return records, skipped


def reproduced_ids(root: Path) -> set[str]:
    path = root / "results" / "reproduced.json"
    if not path.exists():
        return set()
    return set(json.loads(path.read_text(encoding="utf-8")).get("submission_ids", []))


def _attempts(record: dict) -> list[dict]:
    """Attempts with the submission id folded into the task key, so pairs never mix runs."""
    sid = record["submission_id"][:12]
    return [
        {**a, "task_id": f"{sid}/{a['task_id']}", "cost_usd_est": None} for a in record["attempts"]
    ]


def build_leaderboard(records: list[dict], reproduced: set[str], skipped: list[str]) -> dict:
    groups: dict[tuple, list[dict]] = {}
    for r in records:
        key = (
            r["suite"]["name"],
            r["suite"]["version"],
            r["model"]["backend"],
            r["model"]["name"],
            r["qedcode_version"],
            r["controls"]["qedcode_speed"],
            # bm25 and oracle baselines answer different questions: never pool them
            r["controls"].get("baseline_context", "every project file"),
        )
        groups.setdefault(key, []).append(r)
    rows = []
    for key in sorted(groups):
        members = groups[key]
        attempts = [a for r in members for a in _attempts(r)]
        n_repro = sum(r["submission_id"] in reproduced for r in members)
        per = {
            c: summarize_condition([a for a in attempts if a["condition"] == c])
            for c in ("baseline", "qedcode")
        }
        for summary in per.values():
            summary.pop("cost_usd_est", None)
        rows.append(
            {
                "suite": f"{key[0]} {key[1]}",
                "model": key[3],
                "backend": key[2],
                "qedcode_version": key[4],
                "qedcode_speed": key[5],
                "baseline_context": key[6],
                "submissions": len(members),
                "reproduced_submissions": n_repro,
                "label": REPRODUCED if n_repro == len(members) else COMMUNITY,
                "baseline": per["baseline"],
                "qedcode": per["qedcode"],
                "paired": paired(attempts),
                "submission_ids": sorted(r["submission_id"] for r in members),
            }
        )
    return {
        "schema_version": 1,
        "accepted_submissions": len(records),
        "reproduced_submissions": sum(r["submission_id"] in reproduced for r in records),
        "skipped_invalid": skipped,
        "last_run_date": max((r["run_date"] for r in records), default=None),
        "groups": rows,
        "notes": [
            "Community-reported results passed schema and consistency checks; that does not "
            "prove a run happened as described.",
            "Independently reproduced = a maintainer re-ran it and listed it in "
            "results/reproduced.json.",
            "Rates come with 95% Wilson intervals; pairs are the same task and repetition "
            "within one submission.",
        ],
    }


def _pct(x) -> str:
    return "–" if x is None else f"{x * 100:.1f}%"


def readme_block(board: dict) -> str:
    if not board["groups"]:
        return (
            f"{START}\n_No community results yet. Run `benchy run`, then `benchy share` to "
            f"preview what a contribution contains._\n{END}"
        )
    lines = [
        START,
        f"Accepted runs: **{board['accepted_submissions']}** "
        f"(independently reproduced: {board['reproduced_submissions']}) · "
        f"latest run: {board['last_run_date']}",
        "",
        "| suite | model | QEDCode | pairs | baseline resolved | QEDCode resolved | "
        "regressions (base / QED) | label |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for g in board["groups"]:
        b, q, p = g["baseline"], g["qedcode"], g["paired"] or {"pairs": 0}
        lines.append(
            f"| {g['suite']} | {g['model']} | {g['qedcode_version']} {g['qedcode_speed']} | "
            f"{p['pairs']} | {_pct(b['resolution_rate'])} | {_pct(q['resolution_rate'])} | "
            f"{_pct(b['regression_rate'])} / {_pct(q['regression_rate'])} | {g['label']} |"
        )
    lines += ["", "_Generated by `bot/aggregate.py` from `results/submissions/`._", END]
    return "\n".join(lines)


def update_readme(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit(f"README.md needs the markers {START} and {END}.")
    before, rest = text.split(START, 1)
    _old, after = rest.split(END, 1)
    return before + block + after


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    root = args.root
    records, skipped = load_accepted(root)
    board = build_leaderboard(records, reproduced_ids(root), skipped)
    board_text = json.dumps(board, indent=2, sort_keys=True) + "\n"
    readme_path = root / "README.md"
    readme_text = update_readme(readme_path.read_text(encoding="utf-8"), readme_block(board))
    board_path = root / "leaderboard" / "leaderboard.json"
    current = board_path.read_text(encoding="utf-8") if board_path.exists() else ""
    stale = current != board_text or readme_path.read_text(encoding="utf-8") != readme_text
    if args.check:
        print("out of date: run python3 bot/aggregate.py" if stale else "up to date")
        return 1 if stale else 0
    board_path.parent.mkdir(parents=True, exist_ok=True)
    board_path.write_text(board_text, encoding="utf-8")
    readme_path.write_text(readme_text, encoding="utf-8")
    print(f"{len(records)} accepted submission(s), {len(skipped)} skipped as invalid.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
